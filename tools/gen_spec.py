#!/usr/bin/env python3
"""Generate spec/constants.py from spec/undertone.toml, or check that it is current.

    python tools/gen_spec.py            write spec/constants.py
    python tools/gen_spec.py --check    exit 1, naming the first difference, if it is stale
    --root DIR                          work on another copy of the tree

One definition, generated copies. Round 2 adds the SystemVerilog and C outputs
here; today there is one output, the Python constants model/ and stats/ import.

The definition is checked before anything is written, and a definition that
does not make sense is REFUSED by name: an unknown key, a width out of range,
a duplicate name, a flag bit used twice, a pulse that does not fit a profile.
"""
import hashlib
import os
import sys
import tomllib

OUT = "spec/constants.py"
SRC = "spec/undertone.toml"
TOP = {"meta", "profile", "core", "quantise", "records", "flags", "refusals", "pulses"}


class Refused(Exception):
    pass


def load(root):
    with open(os.path.join(root, SRC), "rb") as f:
        raw = f.read()
    d = tomllib.loads(raw.decode("utf-8"))
    if set(d) != TOP:
        raise Refused("UNKNOWN-OR-MISSING-SECTION: %s" % sorted(set(d) ^ TOP))
    for name, p in d["profile"].items():
        if set(p) != {"sample_bits", "channels"}:
            raise Refused("PROFILE-KEYS: %s" % name)
        if not (2 <= p["sample_bits"] <= 32 and 1 <= p["channels"] <= 16):
            raise Refused("PROFILE-RANGE: %s" % name)
    c = d["core"]
    if set(c) != {"coeff_bits", "max_filters", "max_taps"} or min(c.values()) < 1:
        raise Refused("CORE-KEYS-OR-RANGE")
    if d["quantise"] != {"scale": "peak_to_max", "rounding": "half_to_even"}:
        raise Refused("QUANTISE-RULE-UNKNOWN: this generator knows one rule")
    for rec, fields in d["records"].items():
        names = [f[0] for f in fields]
        if len(set(names)) != len(names):
            raise Refused("RECORD-DUPLICATE-FIELD: %s" % rec)
        for f in fields:
            if len(f) != 3 or f[2] not in ("signed", "unsigned") or not 1 <= f[1] <= 64:
                raise Refused("RECORD-FIELD: %s.%s" % (rec, f[0]))
    flag_bits = dict(d["records"]["score"] and [(f[0], f[1]) for f in d["records"]["score"]])["flags"]
    if len(set(d["flags"].values())) != len(d["flags"]) or \
            not all(0 <= b < flag_bits for b in d["flags"].values()):
        raise Refused("FLAG-BITS: a bit is used twice or lies outside the flags field")
    names = d["refusals"]["names"]
    if len(set(names)) != len(names) or not all(n.isupper() or "_" in n for n in names):
        raise Refused("REFUSAL-NAMES")
    pulses = {}
    for name, rel in d["pulses"].items():
        with open(os.path.join(root, "spec", rel), "rb") as f:
            p = tomllib.loads(f.read().decode("utf-8"))
        if p.get("name") != name or not p.get("samples") or \
                not all(isinstance(v, int) for v in p["samples"]):
            raise Refused("PULSE-FILE: %s" % rel)
        pulses[name] = list(p["samples"])
    lo = min(d["profile"].values(), key=lambda p: p["sample_bits"])["sample_bits"]
    for name, s in pulses.items():
        if max(abs(v) for v in s) > 2 ** (lo - 1) - 1:
            raise Refused("PULSE-RANGE: %s does not fit the narrowest profile" % name)
    return d, pulses, hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest()


def render(d, pulses, digest):
    L = ['"""GENERATED by tools/gen_spec.py from spec/undertone.toml. Do not edit.',
         "",
         "Edit the definition, run the generator, commit both. The `generated` stage",
         'of verify/run.sh fails when this file and the definition disagree.',
         '"""',
         "",
         "SPEC_VERSION = %d" % d["meta"]["spec_version"],
         'SPEC_SHA256 = "%s"' % digest,
         "",
         "PROFILES = {"]
    for name in sorted(d["profile"]):
        p = d["profile"][name]
        b = p["sample_bits"]
        L.append('    "%s": {"sample_bits": %d, "channels": %d, "sample_min": %d, "sample_max": %d},'
                 % (name, b, p["channels"], -2 ** (b - 1), 2 ** (b - 1) - 1))
    c = d["core"]
    L += ["}",
          "",
          "COEFF_BITS = %d" % c["coeff_bits"],
          "COEFF_MIN = %d" % -2 ** (c["coeff_bits"] - 1),
          "COEFF_MAX = %d" % (2 ** (c["coeff_bits"] - 1) - 1),
          "MAX_FILTERS = %d" % c["max_filters"],
          "MAX_TAPS = %d" % c["max_taps"],
          "",
          'QUANTISE_SCALE = "%s"' % d["quantise"]["scale"],
          'QUANTISE_ROUNDING = "%s"' % d["quantise"]["rounding"],
          "",
          "RECORDS = {"]
    for rec in sorted(d["records"]):
        L.append('    "%s": (' % rec)
        for f in d["records"][rec]:
            L.append('        ("%s", %d, "%s"),' % (f[0], f[1], f[2]))
        L.append("    ),")
    L += ["}", "", "FLAGS = {"]
    for name in sorted(d["flags"], key=lambda n: d["flags"][n]):
        L.append('    "%s": %d,' % (name, d["flags"][name]))
    flag_bits = [f[1] for f in d["records"]["score"] if f[0] == "flags"][0]
    used = sum(1 << b for b in d["flags"].values())
    L += ["}",
          "FLAGS_RESERVED_MASK = 0x%02X" % (((1 << flag_bits) - 1) & ~used),
          "",
          "REFUSALS = ("]
    L += ['    "%s",' % n for n in d["refusals"]["names"]]
    L += [")", "", "PULSES = {"]
    for name in sorted(pulses):
        s = pulses[name]
        L.append('    "%s": (' % name)
        for i in range(0, len(s), 8):
            L.append("        " + ", ".join(str(v) for v in s[i:i + 8]) + ",")
        L.append("    ),")
    L += ["}", ""]
    return "\n".join(L)


def check(root):
    """Returns a list of findings, each (file, what). Empty means current."""
    try:
        want = render(*load(root))
    except Refused as e:
        return [(SRC, "REFUSED %s" % e)]
    path = os.path.join(root, OUT)
    if not os.path.exists(path):
        return [(OUT, "is missing")]
    with open(path, "rb") as f:
        have = f.read().decode("utf-8").replace("\r\n", "\n")
    if have == want:
        return []
    a, b = have.split("\n"), want.split("\n")
    for i in range(max(len(a), len(b))):
        if i >= len(a) or i >= len(b) or a[i] != b[i]:
            return [(OUT, "differs from the definition at line %d: has %r, the definition gives %r"
                     % (i + 1, a[i] if i < len(a) else None, b[i] if i < len(b) else None))]
    return [(OUT, "differs from the definition")]


def main(argv):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    if "--root" in argv:
        root = os.path.abspath(argv[argv.index("--root") + 1])
    if "--check" in argv:
        findings = check(root)
        for name, what in findings:
            print("FINDING generated %s: %s" % (name, what))
        return 1 if findings else 0
    try:
        text = render(*load(root))
    except Refused as e:
        print("REFUSED %s" % e)
        return 2
    with open(os.path.join(root, OUT), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
